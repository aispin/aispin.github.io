/**
 * 休息机位 —— **首屏**那一点，也是"退出屋子之后回到的那一点"。
 * ==================================================================
 *
 * WO-33a（用户 2026-10-15）：「页面的初始镜头位置往后调整，让飞机和房子
 * 刚好可以展示出来」。
 *
 * 🔴 为什么要有这个文件：这个数字**以前散在四处**，改一处就漂
 * -----------------------------------------------------------------
 * `z = 28` 原本硬编码在：
 *   ① `App.jsx` 的 `<Canvas camera={{ position: [0, 0.2, 28] }}>`
 *   ② `useInfiniteCamera.js` 的 `targetZ` / `currentZ` 两个 `useRef` 初值
 *   ③ `HouseExit.jsx` 的 `OUTSIDE`（退出屋子时 GSAP 补间的目标）
 *   ④ `harness/probe-sky-clouds.mjs` 里写死的 `CAMERA_POS`（判据自带 config，
 *      正是 §28.1 禁的那种）
 * ① 和 ② 不一致 ⇒ **第一帧在旧机位、第二帧瞬移到新机位**（一帧的抖动，
 * 截图看不出来，但探针逐像素比对会看到）。所以这里定成**唯一真源**，
 * 四处都 import 它。
 *
 * 为什么是 45（**量出来的**，不是拍的）
 * ------------------------------------
 * 用户要「飞机和房子**刚好**可以展示出来」。先量了现状：休息机位 z = 28，
 * 而 `airplane` 的世界包围盒是 `z[27.35, 32.95]`、`sakura-tree` 是
 * `z[29.28, 32.07]` —— **两者整个在相机背后**（相机朝 −z 看）。
 * 所以首屏只有砖墙 + 柿子树，"往后"是唯一解，不是偏好。
 *
 * 然后在真页面里扫 z、把两个包围盒的 8 个角投影到 NDC
 * （`harness/wo33-probe.mjs`），取"两个都完整落在 [−1,1] 且有余量"的最小值：
 *
 * | z  | 屋壳 NDC x        | 屋壳 NDC y        | 飞机 NDC x        | 飞机左翼余量 |
 * | --- | --- | --- | --- | --- |
 * | 38 | ±0.787            | −0.254 ~ **1.021** ✗ 屋脊出框 | −1.696 ~ −0.342 ✗ | −0.696 |
 * | 40 | ±0.693            | −0.223 ~ 0.901 ✓  | −1.215 ~ −0.288 ✗ | −0.215 |
 * | 42 | ±0.620            | −0.198 ~ 0.806 ✓  | −0.947 ~ −0.249 ✓  | 0.053（太贴边）|
 * | **45** | **±0.579**     | **−0.185 ~ 0.753** | **−0.711 ~ −0.233** | **0.289** |
 * | 48 | ±0.470            | −0.147 ~ 0.614    | −0.569 ~ −0.176   | 0.431 |
 *
 * 取 **45** 而不是 42 的**第二个理由**（这条才是决定性的）：
 * `fov` 是**竖向**的 60°，视口一窄横向视野就缩水。42 只在 16:9 上够，
 * 4:3 时飞机的左翼尖会出框（NDC −1.03）；45 在 4:3 上是 −0.948，**刚好**
 * 卡住 —— 这才是"刚好可以展示出来"的字面意思。
 *
 * ⚠️ 连带的、已经核对过的两件事：
 *   · **雾**：秋日 `fogNear 22 / fogFar 128`（`seasonLight.js`），屋子在
 *     22.9 处 ⇒ 几乎不进食雾；冬夜 `17 / 96` 也只有极轻一层。**不用动雾**。
 *   · **环绕相机接手不跳**（WO-1 的硬判据）：`useOrbitCamera.adopt()` 从
 *     相机当前位置反算轨道姿态。轴心 z 使 r = 45 − 10.15 = **34.85**，
 *     仍在 `[ORBIT_MIN_R 18, ORBIT_MAX_R 38]` 内 ⇒ **不触发夹取**。
 *     而"正面 yaw=0 时轨道相机落在 z = 28.15"那句注释讲的是 `ORBIT_MIN_R`
 *     的下限位置，与本机位无关（见 `config/island.js` 的 `ORBIT_MIN_R` 段）。
 */
export const REST_POSE = Object.freeze({ x: 0, y: 0.2, z: 45 });

/**
 * 休息机位看向哪 —— **相对量**，不是绝对坐标。
 *
 * `useInfiniteCamera` 每帧写的是
 * `camera.lookAt(lookX, 0.13 + parallax.y, camera.position.z - REST_LOOK_AHEAD)`，
 * 即"朝 −z 看、并下压 `(y − 0.13) / REST_LOOK_AHEAD`"。写成相对量是为了让
 * **俯仰角与 z 无关** —— 机位往后拉时地平线在画幅里的高度不会跟着变。
 * 反过来，若写成绝对 z，改 `REST_POSE.z` 就会连带改掉俯仰（首屏要么多一片
 * 前景草地、要么多一片天），那是**静默**的构图漂移。
 */
export const REST_LOOK_AHEAD = 10;
export const REST_LOOK_Y = 0.13;
