/* ---- 室内（走廊）的前端面 ----------------------------------------- */

/**
 * 🔴 这是全项目**唯一**允许「外观 → 室内」的依赖，方向不能反过来。
 *
 * 走廊是无限循环的，它自己没有"起点"。但它的可见几何（暖白顶 / 墨墙 /
 * 地板）**不能露到露天的前院里** —— 一露出来，从上方看就是院子正中间
 * 一大片暖白顶（还带墨色远山剪影），而前院本该是露天的。这是 L1 背面
 * 清单 + 射线取证（`.workbuddy-ai/harness/probe-court-top.mjs`）抓到的
 * 头号洞：`|x| ≤ 3.5` 那条带上最上面一层永远是
 * `PlaneGeometry{7,10}` @ `y = FLOOR_Y + 3.5`、`side: 2`。
 *
 * 为什么是「建筑定线、走廊服从」：物理上室内不能比房子更靠外。所以由屋身
 * 的前墙定下这条线，走廊的**段相位**从这里往回排 ——
 * `zOffset = INTERIOR_FRONT_Z − segmentIndex × SEGMENT_LENGTH`。
 *
 * 🔴 这样排的额外好处：段 0 的前沿**正好**落在屋身前墙上，于是未入场时
 * 只要把段号 < 0 的整段摘掉，走廊就一根线都不进前院，而且**不需要 zClip**
 * —— 裁剪面与段前沿重合，入场前后几何逐位一致，`hasEntered` 翻转时不会跳。
 *
 * ⚠️ 改这个数 = 同时改**走廊段相位 + 屋身前墙 + 大门 + 入场落点**。一起动。
 */
export const INTERIOR_FRONT_Z = HOUSE_FRONT_Z;

