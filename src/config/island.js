/**
 * 孤岛：一栋老房子 + 门前竹篱笆小院 + 竹林沙滩的全部尺寸，只写一遍。
 * ==================================================================
 *
 * 为什么单独一个文件（照抄 `config/entranceMetrics.js` 的规矩）
 * ----------------------------------------------------------
 * 场景要能绕着看，就多出一整圈东西：岛、沙滩、海、屋身、篱笆、竹林。
 * 它们的尺寸互相咬合 —— 屋身的进深决定岛心，岛心决定相机绕的轴心，
 * 轴心又决定了轨道半径的下限（不能穿进屋里）。任何一个数写在某个组件里，
 * 另一个组件就会悄悄错位。所以：**派生，不重打**。
 *
 * 平面布局（俯视，+z 朝向访客进来的方向）
 * --------------------------------------
 *
 *                          z = 38.15   ← 竹篱笆（前院最外一道，中间留门）
 *                             │
 *         ┌───────────────────┼───────────────────┐   x = ±11
 *         │            前院 (0, 30.15)            │
 *         └───────────────────┼───────────────────┘
 *                          z = 22.15   ← 🔴 屋身**前墙** = 大门 = 走廊前端
 *                             │
 *                   屋身 (0, 10.15)，进深 24
 *                             │
 *                          z = -1.85   ← 屋身后墙
 *                     z = -14.85 …   ← 沙滩 / 海
 *
 * 🔴 v1.2 第二轮改向（2026-10-11，用户三条定案）
 * ---------------------------------------------
 * 上一轮是「院墙围出来的露天院子 + 院子正前方一座独立的门楼」，用户否掉了：
 *
 *   「我意思删删掉院子，直接是老房子」
 *   「① 把房子外观搞高一点，门楼调低一点，然后将房子前门和门楼合二为一。
 *     ② 在前门外面再拓展一个开放的小院子（用竹篱笆）…
 *     ③ 镜头默认在前门（和现在一样，能看到大门、对联、柿子树）。
 *        如果后退，能进入我们的小院子。」
 *
 * 所以现在只有**一栋房子**：门楼不再是一座独立的小楼，它就是屋身的前墙
 * （门洞 + 匾额 + 对联都长在这面墙上，见 `HouseShell` / `EntranceDoors`）。
 * 院子也从"屋前的露天院墙"变成了"**门外的**竹篱笆小院"。
 *
 * 相机绕**屋身中心**转。这样一圈 360° 里每一处都在屋子外面，
 * 不会出现"转到某一侧突然站在屋里"。
 *
 * 🔴 雾就是世界边界（这条决定了下面所有半径）
 * ------------------------------------------
 * `config/seasonLight.js` 里 fogFar 只有 36（冬夜）~66（春）。也就是说
 * **离相机 36 单位外已经是纯雾色**。所以：
 *   · 岛做到半径 36 就够 —— 再远的地形、远山、远处的海**根本看不见**；
 *   · 相机轨道半径上限 28 —— 再远屋子就被雾吃掉（冬夜 fogFar 只有 36）。
 * 这两条一起，省掉了一整个天空盒 + 远景 LOD 系统。
 */

import { FLOOR_Y, GRASS_Y } from './entranceMetrics';

/* ---- 屋身（"老房子"本体）------------------------------------------ */

/**
 * 屋身**不是**照走廊尺寸反推出来的壳 —— 那正是 v1.2 的老做法
 * （`HALL_HALF_W = 3.5 + 0.4`、`HALL_EAVE_Y = FLOOR_Y + 3.5 + 0.45`），
 * 用户明确否掉了：
 *
 *   「只需做一个老房子3D模型，不需要依据内部通道去还原。意思是房子的外观
 *     和房间内部的通道不绑定。因为我们内部实际上是无限循环的。」
 *
 * 所以这里的每个数都按**建筑本身**定，走廊只是恰好从它里面穿过去。
 * 唯一保留的硬约束：屋身必须包住走廊的横截面（半宽 3.5 / 顶高
 * FLOOR_Y + 3.5 = 1.75），否则走廊会从屋面里穿出来。
 *
 * 形制照用户给的参考图（`参考屋形即可`）：**双坡顶，屋脊与屋身正面平行
 * （沿 x）**，两坡分别朝前院（+z）和背院（−z）；檐口向前院出挑、压在小院
 * 上方，檐下露椽头。正面就是那面开着大门、挂着对联的墙。
 */
export const HOUSE_HALF_W = 11;

/**
 * 🔴 前墙所在的世界 z —— 也是**原来的门楼线**（`ENTRANCE_DOORS_Z` 22 +
 * facade 局部 0.15）。门楼合进屋身之后，这条线同时是三件事：
 *   · 屋身的前墙平面；
 *   · 大门（门洞 / 门扇 / 门框 / 对联 / 匾额）所在的平面；
 *   · **走廊的段相位基准**（见下面的 `INTERIOR_FRONT_Z`）。
 * 三者必须逐位重合，否则从门洞往里看会看见墙与走廊之间的一道缝。
 */
export const HOUSE_FRONT_Z = 22.15;

/**
 * 屋身进深 24（后端 −1.85）。
 *
 * ⚠️ 这个数**纯粹是"好不好看"**，不是"要藏走廊"。走廊从 `HOUSE_FRONT_Z`
 * 一路铺到 −∞，屋身只是它的前景遮罩，永远不可能把它整个罩住 —— 真正
 * 让管子不被看见的是「走廊只在人在里面时渲染」（见 `InfiniteCorridorManager`
 * 的封口②）。所以进深按建筑本身定：22 宽 × 24 深、配 0.35 的坡，
 * 屋脊落在 7.63，正面看是一栋两层高的老屋，不是谷仓。
 */
export const HOUSE_DEPTH = 24;
export const HOUSE_BACK_Z = HOUSE_FRONT_Z - HOUSE_DEPTH;

/** 檐口高度（墙头）。比走廊顶（FLOOR_Y + 3.5 = 1.75）高 1.5，走廊藏得进去。 */
export const HOUSE_EAVE_Y = FLOOR_Y + 5.0;
/** 出檐：屋面比墙身多伸出去多少。朝前院那一侧就是压在篱笆小院上方的檐。 */
export const HOUSE_OVERHANG = 0.9;
/** 屋面坡度（弧度）。用户要"房子搞高一点"，0.27 → 0.35。 */
export const HOUSE_PITCH = 0.35;

/** 屋身进深（前墙 → 后端）。 */
export const HOUSE_LEN = HOUSE_FRONT_Z - HOUSE_BACK_Z;
/**
 * 屋脊高度。
 * 🔴 只由**墙长的一半**推出来，不含出檐 —— 屋面在墙平面上的高度就是檐口，
 * 出檐是**往墙外**继续往下走的（屋脊 → 墙顶 → 出檐端，一条直线）。
 * 把出檐算进升幅会让屋面在墙头处高出一截，山墙就接不上了。
 */
export const HOUSE_RIDGE_Y = HOUSE_EAVE_Y + Math.tan(HOUSE_PITCH) * (HOUSE_LEN / 2);
/** 出檐端的高度（比檐口低，因为屋面往墙外继续下坡）。 */
export const HOUSE_EAVE_TIP_Y = HOUSE_EAVE_Y - Math.tan(HOUSE_PITCH) * HOUSE_OVERHANG;

/** 墙高（草地 → 墙头）与墙头压顶线。`HouseShell` 与藤蔓 overlay 共用。 */
export const HOUSE_WALL_H = HOUSE_EAVE_Y - GRASS_Y;
/** 压顶（黑瓦）占墙高的比例 —— 与 `SONG_WALL_FRAG` 的 uCapFrac 同义。 */
export const HOUSE_WALL_CAP_FRAC = 0.905;
/** 压顶**下沿**的世界 y。藤蔓 overlay 从这条线后面钻出来（见 EntranceDoors）。 */
export const HOUSE_COPING_Y = GRASS_Y + HOUSE_WALL_H * HOUSE_WALL_CAP_FRAC;

/** 屋身中心 z —— 环绕相机的轴心用它。 */
export const HOUSE_CENTER_Z = (HOUSE_FRONT_Z + HOUSE_BACK_Z) / 2;

/**
 * 竹林要避开的"建筑带"：`|x| < 12` 且 z 落在 [屋身后墙 − 1, 篱笆 + 1]。
 * 22 宽的屋身 + 16 深的前院连起来是一条 42 长的带子，窄了竹子会从屋里
 * / 院里长出来。见 `BambooGrove.buildGrove`。
 */
export const HOUSE_CLEAR_HALF_W = HOUSE_HALF_W + 1;

/* ---- 前院（竹篱笆围的开放小院，门**外**）-------------------------- */

/**
 * 前院：`x ∈ [−11, 11]`、`z ∈ [22.15, 38.15]`（16 深）。
 * 篱笆只围**外三面**（左右 + 正前），内面就是屋身的前墙。
 * 摆设（石桌 / 花箱 / 缸 / 狗）按用户说的"后话"，暂时沿用门口的几件。
 */
export const FORECOURT_HALF_W = HOUSE_HALF_W;
export const FORECOURT_DEPTH = 16;
export const FORECOURT_BACK_Z = HOUSE_FRONT_Z + FORECOURT_DEPTH;
export const FORECOURT_CENTER_Z = (HOUSE_FRONT_Z + FORECOURT_BACK_Z) / 2;
/** 正前方那道篱笆上给甬路留的开口（半宽）。甬路 width ≈ 3.06，取 1.7 刚好包住。 */
export const FORECOURT_GATE_HALF_W = 1.7;
/** 篱高。真篱笆齐腰以下 —— 环绕相机最低机位（y ≈ 0.46）不会被它糊住下半屏。 */
export const FORECOURT_FENCE_H = 0.62;

/** 建筑带的另一端（篱笆外 1 单位）。竹林避开 [HOUSE_BACK_Z − 1, 这里]。 */
export const HOUSE_CLEAR_BACK_Z = FORECOURT_BACK_Z + 1;

/* ---- 岛 ---------------------------------------------------------- */

/** 岛心 = 建筑带（屋身后墙 ↔ 篱笆前缘）的中点。 */
export const ISLAND_CENTER = [0, (HOUSE_BACK_Z + FORECOURT_BACK_Z) / 2];

/**
 * 草地半径 30。要盖住整条建筑带：最远的两个角是
 * (±11, −1.85) 与 (±11, 38.15)，离岛心都是 22.8 ⇒ 30 留了一圈草地。
 */
export const ISLAND_GRASS_R = 30;
/** 岸线半径（含噪声摆动 ±5）。30~36 这一圈是沙滩。 */
export const ISLAND_SAND_R = 36;
/** 地面平面尺寸。半宽 60 足够盖住"相机在最外圈朝外看"的全部范围。 */
export const GROUND_SIZE = 120;

/** 地面世界高度 —— 与草坪同高（GRASS_Y = −2.09）。 */
export const GROUND_Y = GRASS_Y;

/* ---- 环绕相机（DR-B：B1 受限轨道 + B2 边界）---------------------- */

/**
 * 轴心 = 屋身中心，y 保持 `FLOOR_Y + 1.9 = 0.15` —— 和入场机位的 y（0.2）
 * 几乎同高，所以环绕模式接手时画面几乎不动（"接手不跳"是 WO-1 的判据）。
 *
 * ⚠️ 屋子长高到 7.63 之后这个 y 显得偏低（lookAt 落在屋子竖向中心下方
 * 2.6），但**不能随手抬**：`useOrbitCamera.adopt()` 是在相机还停在
 * (0, 0.2, 28) 时反算姿态的，轴心一抬，仰角就被 `ORBIT_MIN_ELEV` 夹住，
 * 接手那一帧会**往上跳**（实测 0.15 → 1.75 会跳 1.6 单位）。
 * 要看整栋屋子就往后滚（`ORBIT_MAX_R`），不要动这个 y。
 */
export const ORBIT_CENTER = [0, FLOOR_Y + 1.9, HOUSE_CENTER_Z];

/**
 * 轨道半径范围。
 *   · 下限 18：屋身四角离轴心 16.28（半宽 11 / 半深 12），再近就穿进屋里。
 *     顺带：正面（yaw = 0）时相机落在 z = 28.15，离大门 6 单位 —— 和入场
 *     结束时的 5.85 基本一致，而且和 `HouseExit.OUTSIDE.z`（28）几乎重合，
 *     所以"退出去"接"环绕"也不会跳。
 *   · 上限 28：再远屋子进雾（冬夜 fogFar 只有 36）。
 */
export const ORBIT_MIN_R = 18;
export const ORBIT_MAX_R = 28;

/**
 * 仰角范围（弧度，0 = 与轴心同高）。
 *   · 下限 1°：不许钻到地面以下（那里什么都没建模）。
 *   · 上限 50°：再高就变成航拍，屋子和院子的细节全没了。
 */
export const ORBIT_MIN_ELEV = 0.017;
export const ORBIT_MAX_ELEV = 0.873;

/** 相机高度的硬地板。轨道算完再夹一次，双保险。 */
export const ORBIT_MIN_Y = GROUND_Y + 0.9;

/** 滚轮改半径的步长（倍率 / 格）。 */
export const ORBIT_ZOOM_STEP = 0.06;
/** 拖拽灵敏度（弧度 / 像素）。 */
export const ORBIT_DRAG_SPEED = 0.0045;
/** 超过这个像素位移算"拖拽"，否则算"点击" —— 保住"点门进屋"。 */
export const ORBIT_DRAG_THRESHOLD = 6;

/* ---- 室内（走廊）的前端面 ----------------------------------------- */

/**
 * 🔴 这是全项目**唯一**允许「外观 → 室内」的依赖，方向不能反过来。
 *
 * 走廊是无限循环的，它自己没有"起点"。但它的可见几何（暖白顶 / 墨墙 /
 * 地板）**不能露到露天的前院里** —— 一露出来，从上方看就是院子正中间
 * 一大片暖白顶（还带墨色远山剪影），而前院本该是露天的。这是 L1 背面
 * 清单 + 射线取证（`.workbuddy-ai/harness/probe-court-top.mjs`）抓到的
 * 头号洞：`|x| ≤ 3.5` 那条带上最上面一层永远是
 * `PlaneGeometry{7,10}` @ `y = FLOOR_Y + 3.5`、`side: 2`。
 *
 * 为什么是「建筑定线、走廊服从」：物理上室内不能比房子更靠外。所以由屋身
 * 的前墙定下这条线，走廊的**段相位**从这里往回排 ——
 * `zOffset = INTERIOR_FRONT_Z − segmentIndex × SEGMENT_LENGTH`。
 *
 * 🔴 这样排的额外好处：段 0 的前沿**正好**落在屋身前墙上，于是未入场时
 * 只要把段号 < 0 的整段摘掉，走廊就一根线都不进前院，而且**不需要 zClip**
 * —— 裁剪面与段前沿重合，入场前后几何逐位一致，`hasEntered` 翻转时不会跳。
 *
 * ⚠️ 改这个数 = 同时改**走廊段相位 + 屋身前墙 + 大门 + 入场落点**。一起动。
 */
export const INTERIOR_FRONT_Z = HOUSE_FRONT_Z;

/* ---- 竹林 -------------------------------------------------------- */

/** 竹子根数（低画质档砍到 40%）。 */
export const BAMBOO_COUNT_HIGH = 420;
export const BAMBOO_COUNT_LOW = 160;
/**
 * 竹林的环带：离岛心 24~31（草地外圈、沙滩内缘）。
 * ⚠️ 下限不能小于 24：建筑带（|x| < 12 且 z ∈ [−2.85, 39.15]）离岛心最远
 * 的角是 24.2，环带再往里就会被整条建筑带吃掉 —— 一根竹子都不剩。
 */
export const BAMBOO_R_MIN = 24;
export const BAMBOO_R_MAX = 31;
/** 竹竿高度范围（世界单位）。 */
export const BAMBOO_H_MIN = 4.2;
export const BAMBOO_H_MAX = 7.6;
/** 风摆幅度（世界单位，顶端最大位移）。 */
export const BAMBOO_WIND = 0.34;
/** 每根竹子的叶片数。 */
export const BAMBOO_BLADES_PER_CULM = 3;
